import 'dart:convert';
import 'dart:io';

import '../../frontend/lib/features/learning/data/school_review_data.dart';

void main(List<String> args) {
  const json = JsonEncoder.withIndent('  ');
  final subject = schoolReviewSubject;
  final output = File.fromUri(
    Platform.script.resolve('../../backend/src/data/schoolReview.generated.ts'),
  );
  final catalog = {
    'subject': {
      'id': subject.id,
      'name': subject.name,
      'description': subject.description,
    },
    'topics': [
      for (final topic in schoolReviewTopics)
        {'id': topic.id, 'subjectId': topic.subjectId, 'name': topic.name},
    ],
    'sets': [
      for (final set in schoolReviewSets)
        {
          'id': set.id,
          'subjectId': set.subjectId,
          'topicId': set.topicId,
          'title': set.title,
          'description': set.description,
          'language': set.language,
          'questionCount': set.questionCount,
        },
    ],
    'questions': [
      for (final question in schoolReviewQuestions)
        {
          'id': question.id,
          'questionSetId': question.questionSetId,
          'text': question.text,
          'answerOptions': [
            for (final answer in question.answerOptions)
              {'id': answer.id, 'text': answer.text},
          ],
        },
    ],
    'answers': {
      for (final entry in schoolReviewAnswers.entries)
        entry.key: {
          'optionId': entry.value.optionId,
          'explanation': entry.value.explanation,
        },
    },
  };
  final source =
      '''
// Generated by tools/catalog/sync_school_review.dart.
import type { Question, QuestionSet, Subject, Topic } from '../types/learning.js';

export const schoolReviewCatalog: {
  subject: Subject;
  topics: Topic[];
  sets: QuestionSet[];
  questions: Question[];
  answers: Record<string, { optionId: string; explanation: string }>;
} = ${json.convert(catalog)};
''';
  if (args.contains('--check')) {
    if (!output.existsSync() ||
        output.readAsStringSync().replaceAll('\r\n', '\n') != source) {
      stderr.writeln('School review catalog is out of sync.');
      exitCode = 1;
    }
    return;
  }
  output.writeAsStringSync(source);
}
